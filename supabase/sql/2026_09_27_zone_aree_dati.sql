-- ── tecnici_zone diventa la vista di «oggi», con le stesse righe di prima ──
alter table public.tecnici_zone set schema archivio;
alter table archivio.tecnici_zone rename to bk_2026_09_27_tecnici_zone;

create view public.tecnici_zone with (security_invoker = true) as
with oggi_c as (
  select c.area_id, c.comune_nome, c.quartiere, c.dal
    from public.zone_aree_comuni c
   where c.dal <= current_date and (c.al is null or c.al >= current_date)
), oggi_t as (
  select t.area_id, lower(tc.email) as email
    from public.zone_aree_tecnici t
    join public.tecnici tc on tc.tecnico_id = t.tecnico_id
   where t.dal <= current_date and (t.al is null or t.al >= current_date)
)
select ot.email,
       case when c.quartiere is null then c.comune_nome
            else 'PADOVA - ' || (array['Q1 Centro','Q2 Nord','Q3 Est','Q4 Sud-Est','Q5 Sud-Ovest','Q6 Ovest'])[c.quartiere] end as comune_nome,
       min(c.dal)::timestamptz as created_at
  from oggi_c c join oggi_t ot on ot.area_id = c.area_id
 group by 1, 2
union
-- «PADOVA» senza quartiere (via non riconosciuta dallo stradario): a chi ha almeno un quartiere
select distinct ot.email, 'PADOVA', min(c.dal)::timestamptz
  from oggi_c c join oggi_t ot on ot.area_id = c.area_id
 where c.quartiere is not null
 group by ot.email;
comment on view public.tecnici_zone is 'Vista (dal 27/09/2026): comuni e quartieri di ogni tecnico OGGI, calcolati da zone_aree_comuni + zone_aree_tecnici. Stesse colonne della vecchia tabella (in archivio.bk_2026_09_27_tecnici_zone). Si modifica dalle tabelle zone_aree_*, non da qui.';
revoke all on public.tecnici_zone from anon;
