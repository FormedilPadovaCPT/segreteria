-- Stessa regola di quartierePadova() del gestionale, parola per parola.
-- Si chiama solo per i cantieri con comune PADOVA (il chiamante lo controlla).
create or replace function public.quartiere_padova(p_indirizzo text)
returns smallint
language plpgsql stable
set search_path = public
as $$
declare
  a   text;
  t   text[];
  srt text;
  n   smallint;
begin
  if p_indirizzo is null then return null; end if;
  -- solo la parte prima di « - », «/», «,», «(»
  a := (regexp_split_to_array(p_indirizzo, '\s+[-–—]\s+|/|,|\('))[1];
  a := translate(lower(a), 'àáâäãèéêëìíîïòóôöõùúûüçñ', 'aaaaaeeeeiiiiooooouuuucn');
  a := replace(a, '''', ' ');
  select array_agg(x order by ord) into t
    from regexp_split_to_table(a, '[^a-z0-9]+') with ordinality as s(x, ord)
   where length(x) > 1
     and x <> all (array['da','de','di','del','dei','degli','della','delle','dal','dalla','lo','la','le','il','i','gli','d','l','a','e','in','con','su','per','san','santa','santo','santi','sant'])
     and x <> all (array['via','piazza','viale','corso','vicolo','largo','ponte','strada','riviera','prato','porta','arco','riva','galleria','piazzale','piazzetta','borgo','lungargine','stradella','cavalcavia','passaggio','rotonda','scalinata','privata','localita','zona','presso']);
  if t is null then return null; end if;
  select string_agg(x, ' ' order by x collate "C") into srt from unnest(t) as x;
  select quartiere into n from stradario_padova where tipo = 's' and chiave = srt;
  if n is null then
    select quartiere into n from stradario_padova where tipo = 's' and chiave = replace(srt, ' ', '');
  end if;
  if n is null then
    select sp.quartiere into n
      from unnest(t) with ordinality as w(x, ord)
      join stradario_padova sp on sp.tipo = 'u' and sp.chiave = w.x
     order by length(w.x) desc, w.ord
     limit 1;
  end if;
  if n is null then
    select sp.quartiere into n
      from unnest(t) with ordinality as w(x, ord)
      join stradario_padova sp on sp.tipo = 'o' and sp.chiave = w.x
     order by w.ord
     limit 1;
  end if;
  return n;
end $$;
comment on function public.quartiere_padova(text) is 'Quartiere di Padova (1..6) da un indirizzo, con lo stradario del gestionale; null se la via non si riconosce. Stessa regola di quartierePadova() in gestionale-visite/index.html.';
revoke execute on function public.quartiere_padova(text) from public;
grant execute on function public.quartiere_padova(text) to authenticated, service_role;

