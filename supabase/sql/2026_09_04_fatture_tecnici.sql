-- ── 1. TARIFFE ──────────────────────────────────────────────
create table if not exists public.s_tariffe (
  id           bigint generated by default as identity primary key,
  codice       text not null,           -- visita_prima | visita_successiva | visita_stage | visita_progetto | docenza_ora | consulenza_ora | conferenza_ora | asseverazione_giorno | coordinamento_ora | altro
  descrizione  text,
  importo      numeric(10,2) not null,
  unita        text not null default 'visita',   -- visita | ora | giorno | forfait
  valido_dal   date not null,
  valido_al    date,
  tecnico_id   text references public.tecnici(tecnico_id),  -- null = vale per tutti
  note         text,
  created_at   timestamptz not null default now(),
  creato_da    text
);
create index if not exists ix_s_tariffe_codice on public.s_tariffe(codice, valido_dal);

-- la tariffa buona per un codice a una data: prima quella del tecnico, poi la generale
create or replace function public.s_tariffa(p_codice text, p_data date, p_tecnico text default null)
returns numeric language sql stable security definer set search_path = public as $$
  select importo from public.s_tariffe
  where codice = p_codice
    and valido_dal <= coalesce(p_data, current_date)
    and (valido_al is null or valido_al >= coalesce(p_data, current_date))
    and (tecnico_id is null or tecnico_id = p_tecnico)
  order by (tecnico_id is not null) desc, valido_dal desc
  limit 1;
$$;

-- ── 2. REGIME FISCALE DEI TECNICI ───────────────────────────
create table if not exists public.s_tecnici_fiscale (
  id          bigint generated by default as identity primary key,
  tecnico_id  text not null references public.tecnici(tecnico_id),
  iva_pct     numeric(5,2) not null default 22,
  cassa_pct   numeric(5,2) not null default 4,
  regime      text,                  -- ordinario | forfettario | …
  valido_dal  date,
  valido_al   date,
  note        text,
  created_at  timestamptz not null default now(),
  creato_da   text
);
create index if not exists ix_s_tecnici_fiscale_tec on public.s_tecnici_fiscale(tecnico_id, valido_dal);

create or replace function public.s_regime_tecnico(p_tecnico text, p_data date default current_date)
returns table (iva_pct numeric, cassa_pct numeric, regime text)
language sql stable security definer set search_path = public as $$
  select f.iva_pct, f.cassa_pct, f.regime from public.s_tecnici_fiscale f
  where f.tecnico_id = p_tecnico
    and (f.valido_dal is null or f.valido_dal <= coalesce(p_data, current_date))
    and (f.valido_al is null or f.valido_al >= coalesce(p_data, current_date))
  order by f.valido_dal desc nulls last
  limit 1;
$$;

