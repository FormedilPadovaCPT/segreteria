-- ── 9. ruolo coordinatore ───────────────────────────────────
create or replace function public.is_coordinatore()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.s_config c
    where c.chiave = 'coordinatore_email'
      and lower(c.valore) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- il tecnico che sta guardando (per le policy «vedo le mie righe»)
create or replace function public.s_mio_tecnico_id()
returns text language sql stable security definer set search_path = public as $$
  select t.tecnico_id from public.tecnici t
  where lower(t.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  order by t.attivo desc limit 1;
$$;

-- ── 10. la pratica mensile tiene allineato il target del gestionale ──
-- (target_visite_mensili è la card «obiettivo del mese» che il tecnico
-- vede già nel gestionale: non si duplica, si alimenta da qui)
create or replace function public.s_inc_mensile_sync_target()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.tecnico_id is not null and new.cantieri_assegnati is not null and new.stato <> 'annullato' then
    insert into public.target_visite_mensili (tecnico_id, anno, mese, max_visite, updated_at)
    values (new.tecnico_id, new.anno, new.mese, new.cantieri_assegnati, now())
    on conflict (tecnico_id, anno, mese) do update set max_visite = excluded.max_visite, updated_at = now();
  end if;
  return new;
end $$;
drop trigger if exists trg_s_inc_mensile_sync_target on public.s_incarichi_mensili;
create trigger trg_s_inc_mensile_sync_target
  after insert or update of cantieri_assegnati, stato on public.s_incarichi_mensili
  for each row when (new.importato_da_access = false) execute function public.s_inc_mensile_sync_target();

-- ── 11. LE PRESTAZIONI DEL MESE, calcolate dalle fonti ──────
-- Restituisce le righe candidate al riepilogo di un tecnico per un
-- mese: visite (dal gestionale), docenze (s_corsi_incarichi), servizi
-- con corrispettivo (incarichi), asseverazioni (a_pratica). Ogni riga
-- dice se è GIÀ registrata in s_prestazioni (e con quale fattura):
-- finché il mese è aperto è un'anteprima, alla chiusura si congela.
create or replace function public.s_prestazioni_calcola(p_tecnico text, p_anno int, p_mese int)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_dal date := make_date(p_anno, p_mese, 1);
  v_al  date := (make_date(p_anno, p_mese, 1) + interval '1 month - 1 day')::date;
  v_email text;
  v_cognome text;
  v_out jsonb := '[]'::jsonb;
begin
  select lower(email), tecnico_cognome into v_email, v_cognome from public.tecnici where tecnico_id = p_tecnico;

  /* a) visite */
  v_out := v_out || coalesce((
    select jsonb_agg(jsonb_build_object(
      'sorgente', 'visita', 'visita_id', v.visita_id, 'nr_verbale', v.nr_verbale,
      'data', v.data_visita, 'stato_visita', v.stato,
      'tipo', t.tipo, 'tariffa_codice', t.tipo,
      'tariffa_unitaria', public.s_tariffa(t.tipo, v.data_visita, p_tecnico),
      'quantita', 1, 'unita', 'visita',
      'importo', public.s_tariffa(t.tipo, v.data_visita, p_tecnico),
      'descrizione', concat_ws(' — ', coalesce(i.impresa_nome, v.impresa_rl_nome), c.comune_nome,
                       case when v.senza_rapporto then 'stage senza rapporto' else null end,
                       case when v.rlst_sn then 'con RLST' else null end),
      'impresa', coalesce(i.impresa_nome, v.impresa_rl_nome), 'comune', c.comune_nome,
      'accesso_n', v.acc_cant, 'tipo_accesso', v.tipo_accesso, 'rlst', v.rlst_sn, 'stage', coalesce(v.stage_vis, false) or v.senza_rapporto,
      'progetto_id', v.progetto_id, 'cantiere_id', v.cantiere_id,
      'prestazione_id', p.id, 'fattura_id', p.fattura_id, 'incarico_mensile_id', p.incarico_mensile_id
    ) order by v.data_visita, v.nr_verbale)
    from public.visite v
    left join public.imprese i on i.impresa_id = v.impresa_id
    left join public.cantieri c on c.cantiere_id = v.cantiere_id
    left join public.s_prestazioni p on p.visita_id = v.visita_id
    cross join lateral (select case
        when v.senza_rapporto or coalesce(v.stage_vis, false) or v.tipo_accesso = 9 then 'visita_stage'
        when v.progetto_id is not null and v.progetto_id not in (14) then 'visita_progetto'
        when coalesce(nullif(regexp_replace(coalesce(v.acc_cant, ''), '\D', '', 'g'), ''), '1')::int > 1 then 'visita_successiva'
        else 'visita_prima' end as tipo) t
    where v.tecnico_id = p_tecnico and v.elimina is distinct from 1
      and v.data_visita between v_dal and v_al
  ), '[]'::jsonb);

  /* a2) visite stage fuori provincia, senza verbale (s_visite_stage) */
  v_out := v_out || coalesce((
    select jsonb_agg(jsonb_build_object(
      'sorgente', 'stage', 'visita_stage_id', s.id,
      'data', s.data, 'tipo', 'visita_stage', 'tariffa_codice', 'visita_stage',
      'tariffa_unitaria', public.s_tariffa('visita_stage', s.data, p_tecnico),
      'quantita', 1, 'unita', 'visita',
      'importo', public.s_tariffa('visita_stage', s.data, p_tecnico),
      'descrizione', concat_ws(' — ', s.azienda, concat_ws(' ', s.comune, case when s.provincia is not null then '(' || s.provincia || ')' end), 'stage fuori provincia senza verbale', case when s.stagista is not null then 'stagista ' || s.stagista end),
      'impresa', s.azienda, 'comune', s.comune, 'stage', true, 'rlst', false, 'tipo_accesso', 9, 'progetto_id', 15,
      'prestazione_id', p.id, 'fattura_id', p.fattura_id, 'incarico_mensile_id', p.incarico_mensile_id
    ) order by s.data)
    from public.s_visite_stage s
    left join public.s_prestazioni p on p.visita_stage_id = s.id
    where s.tecnico_id = p_tecnico and s.stato = 'registrata' and s.data between v_dal and v_al
  ), '[]'::jsonb);

  /* b) docenze (lettere di incarico dei corsi) */
  v_out := v_out || coalesce((
    select jsonb_agg(jsonb_build_object(
      'sorgente', 'docenza', 'corso_incarico_id', k.id, 'corso_id', k.corso_id,
      'data', coalesce(k.data_incarico, c.data_inizio),
      'tipo', 'docenza', 'tariffa_codice', 'docenza_ora',
      'tariffa_unitaria', coalesce(k.tariffa_oraria, public.s_tariffa('docenza_ora', coalesce(k.data_incarico, c.data_inizio), p_tecnico)),
      'quantita', coalesce(k.ore, 0), 'unita', 'ora',
      'importo', coalesce(k.corrispettivo, coalesce(k.ore, 0) * coalesce(k.tariffa_oraria, public.s_tariffa('docenza_ora', coalesce(k.data_incarico, c.data_inizio), p_tecnico))),
      'descrizione', concat_ws(' — ', 'Corso n° ' || k.corso_id, c.titolo),
      'progetto_id', c.progetto_id, 'prot_out_id', k.protocollo_out_id,
      'prestazione_id', p.id, 'fattura_id', p.fattura_id, 'incarico_mensile_id', p.incarico_mensile_id
    ) order by k.data_incarico)
    from public.s_corsi_incarichi k
    join public.s_corsi c on c.id = k.corso_id
    left join public.s_prestazioni p on p.corso_incarico_id = k.id
    where coalesce(k.data_incarico, c.data_inizio) between v_dal and v_al
      and (
        exists (select 1 from public.persone pe join public.tecnici t on lower(t.email) = lower(pe.email) where pe.persona_id = k.persona_id and t.tecnico_id = p_tecnico)
        or (v_cognome is not null and k.nominativo ilike '%' || v_cognome || '%')
      )
  ), '[]'::jsonb);

  /* c) servizi con corrispettivo (incarichi del gestionale) */
  v_out := v_out || coalesce((
    select jsonb_agg(jsonb_build_object(
      'sorgente', 'incarico', 'incarico_id', i.id,
      'data', coalesce(i.eseguito_il::date, i.data_risposta, i.data_richiesta),
      'tipo', case when coalesce(i.tipologia_richiesta, i.tipo_richiesta, i.oggetto, '') ilike '%conferenz%' then 'conferenza'
                   when coalesce(i.tipologia_richiesta, i.tipo_richiesta, i.oggetto, '') ilike '%consulen%' then 'consulenza'
                   else 'altro' end,
      'tariffa_codice', null,
      'tariffa_unitaria', i.corrispettivo, 'quantita', coalesce(i.ore, 1), 'unita', 'ora',
      'importo', i.corrispettivo * coalesce(i.ore, 1),
      'descrizione', concat_ws(' — ', 'Incarico n° ' || i.id, coalesce(i.tipologia_richiesta, i.tipo_richiesta), i.impresa, i.comune),
      'avviso', case when i.visita_id is not null or exists (select 1 from public.visite vv where vv.prot_int = i.id::text)
                     then 'ha una visita collegata: se già conteggiata fra le visite, non aggiungere' else null end,
      'prestazione_id', p.id, 'fattura_id', p.fattura_id, 'incarico_mensile_id', p.incarico_mensile_id
    ) order by i.data_richiesta)
    from public.incarichi i
    left join public.s_prestazioni p on p.incarico_id = i.id
    where lower(coalesce(i.tecnico_email, '')) = coalesce(v_email, '')
      and coalesce(i.corrispettivo, 0) > 0
      and coalesce(i.eseguito_il::date, i.data_risposta, i.data_richiesta) between v_dal and v_al
  ), '[]'::jsonb);

  /* d) asseverazioni (verifica conclusa nel mese) */
  v_out := v_out || coalesce((
    select jsonb_agg(jsonb_build_object(
      'sorgente', 'asseverazione', 'a_pratica_id', a.id, 'numero_protocollo', a.numero_protocollo,
      'data', coalesce(a.data_fine_verifica, a.data_inizio_verifica, a.data_incarico),
      'tipo', 'asseverazione', 'tariffa_codice', 'asseverazione_giorno',
      'tariffa_unitaria', coalesce(a.incarico_tariffa_giornaliera, public.s_tariffa('asseverazione_giorno', coalesce(a.data_fine_verifica, a.data_incarico)::date, p_tecnico)),
      'quantita', coalesce(a.incarico_giornate, 1), 'unita', 'giorno',
      'importo', coalesce(a.incarico_compenso, coalesce(a.incarico_giornate, 1) * coalesce(a.incarico_tariffa_giornaliera, public.s_tariffa('asseverazione_giorno', coalesce(a.data_fine_verifica, a.data_incarico)::date, p_tecnico))),
      'descrizione', concat_ws(' — ', 'Asseverazione ' || coalesce(a.numero_protocollo, ''), a.tipo::text, id_imp.impresa_nome),
      'progetto_id', 18,
      'prestazione_id', p.id, 'fattura_id', p.fattura_id, 'incarico_mensile_id', p.incarico_mensile_id
    ) order by a.data_fine_verifica)
    from public.a_pratica a
    left join public.imprese id_imp on id_imp.impresa_id = a.impresa_id::text
    left join public.s_prestazioni p on p.a_pratica_id = a.id
    where (a.tecnico_principale::text = p_tecnico or a.tecnico_verificatore2::text = p_tecnico)
      and coalesce(a.data_fine_verifica, a.data_inizio_verifica, a.data_incarico)::date between v_dal and v_al
  ), '[]'::jsonb);

  return v_out;
end $$;

-- ── 12. decisione del coordinatore sulla fattura ────────────
create or replace function public.s_fattura_decisione(p_id bigint, p_esito text, p_motivo text default null)
returns public.s_fatture_tecnici language plpgsql security definer set search_path = public as $$
declare v public.s_fatture_tecnici; v_chi text := coalesce(auth.jwt() ->> 'email', 'sistema');
begin
  if not (public.is_coordinatore() or public.is_segreteria()) then raise exception 'Non autorizzato'; end if;
  if p_esito = 'approvata' then
    update public.s_fatture_tecnici set stato = 'approvata', approvata_da = v_chi, approvata_il = current_date,
      standby_motivo = null, updated_at = now(), aggiornato_da = v_chi where id = p_id returning * into v;
  elsif p_esito = 'standby' then
    update public.s_fatture_tecnici set stato = 'standby', standby_motivo = p_motivo, standby_il = now(), standby_da = v_chi,
      updated_at = now(), aggiornato_da = v_chi where id = p_id returning * into v;
  else
    raise exception 'Esito non valido: %', p_esito;
  end if;
  return v;
end $$;

